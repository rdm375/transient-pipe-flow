C     M8 ADAPTIVE IMPLICIT THETA DRIVER. NO STEP DOUBLING.
C     ARGS: OUTPUT_CSV [N] [DURATION] [TOL] [HMAX]
C     TOL IS DIMENSIONLESS TARGET FOR SLOPE-CURVATURE INDICATOR.
      PROGRAM ADAPTINV
      IMPLICIT NONE
      INTEGER N,I,K,INFO,NITER,MAXIT,IOS,REJECT,MAXREJ
      INTEGER ACCEPTED,REJECTED,NTOTAL,STARTUP
      DOUBLE PRECISION PO(0:100),MO(0:99),PN(0:100)
      DOUBLE PRECISION MN(0:99),U(202),PI,D,A,T,Z,RS,MU,EPS
      DOUBLE PRECISION L,DX,H,HMAX,HMIN,TIME,DURATION,TNEXT
      DOUBLE PRECISION THETA,PIN,MDOT0,MDOT1,TRAMP
      DOUBLE PRECISION MINO,MOUTO,MOUTN,RE,FD0,COEF0,X
      DOUBLE PRECISION RTOL,STOL,MASS0,MASS1,BAL,CUMDEF
      DOUBLE PRECISION DEMAND_RAMP,REYNOLDS_MASS,FRICTION_SJ
      DOUBLE PRECISION PREV(202),CUR(202),SLOPE(202),OLDS(202)
      DOUBLE PRECISION HPREV,ETA,TOL,ATOL,RTOLY,SCALE,VAL
      DOUBLE PRECISION QOLD,QNEW,QPREV,QERR,MERR,OLDMASS
      DOUBLE PRECISION FAC,CFL,CS,HSCHEDULE,HFLOOR
      CHARACTER*256 ARG,OUTFILE
      CALL GET_COMMAND_ARGUMENT(1,OUTFILE)
      IF (LEN_TRIM(OUTFILE).EQ.0) STOP 2
      N=20
      CALL GET_COMMAND_ARGUMENT(2,ARG)
      IF (LEN_TRIM(ARG).GT.0) READ(ARG,*) N
      DURATION=3600D0
      CALL GET_COMMAND_ARGUMENT(3,ARG)
      IF (LEN_TRIM(ARG).GT.0) READ(ARG,*) DURATION
      TOL=0.01D0
      CALL GET_COMMAND_ARGUMENT(4,ARG)
      IF (LEN_TRIM(ARG).GT.0) READ(ARG,*) TOL
      HMAX=120D0
      CALL GET_COMMAND_ARGUMENT(5,ARG)
      IF (LEN_TRIM(ARG).GT.0) READ(ARG,*) HMAX
      IF (N.LT.2.OR.N.GT.100.OR.TOL.LE.0D0.OR.
     &    HMAX.LE.0D0.OR.DURATION.LE.0D0) STOP 2
      PI=4D0*DATAN(1D0)
      D=1D0
      A=PI*D*D/4D0
      T=288.15D0
      Z=0.90D0
      RS=500D0
      MU=1.1D-5
      EPS=4.5D-5
      L=100000D0
      DX=L/DBLE(N)
      THETA=0.65D0
      PIN=8D6
      MDOT0=100D0
      MDOT1=105D0
      TRAMP=600D0
      RTOL=1D-11
      STOL=1D-12
      MAXIT=30
      RE=REYNOLDS_MASS(MDOT0,D,A,MU)
      FD0=FRICTION_SJ(RE,EPS,D)
      COEF0=FD0*Z*RS*T*MDOT0*MDOT0/(D*A*A)
      DO 10 I=0,N
         X=DBLE(I)*DX
         PO(I)=DSQRT(PIN*PIN-COEF0*X)
   10 CONTINUE
      DO 20 I=0,N-1
         MO(I)=MDOT0
   20 CONTINUE
      MINO=MDOT0
      MOUTO=MDOT0
      CALL LINEPACK_CZ(N,PO,DX,A,T,Z,RS,MASS0)
      OLDMASS=MASS0
      QOLD=0D0
      QPREV=0D0
      HPREV=0D0
      STARTUP=1
      PREV(1)=PIN
      PREV(2)=MINO
      DO 25 I=0,N-1
         PREV(2*I+3)=MO(I)
         PREV(2*I+4)=PO(I+1)
   25 CONTINUE
      TIME=0D0
      CUMDEF=0D0
      ACCEPTED=0
      REJECTED=0
      NTOTAL=0
      MAXREJ=20
      HMIN=1D-5
      HFLOOR=HMIN
      H=DMIN1(HMAX,TRAMP/8D0,DX/DSQRT(Z*RS*T))
      CS=DSQRT(Z*RS*T)
      OPEN(UNIT=31,FILE=TRIM(OUTFILE),STATUS='REPLACE',
     &     ACTION='WRITE',IOSTAT=IOS)
      IF (IOS.NE.0) STOP 3
      WRITE(31,'(A)') 'time_s,dt_s,inventory_kg,inlet_kg_s,'//
     & 'outlet_kg_s,imbalance_kg_s,inventory_rate_kg_s,'//
     & 'step_balance_defect_kg,cumulative_defect_kg,'//
     & 'outlet_pressure_pa,newton_iterations,indicator,'//
     & 'rejects_before_accept,acoustic_cfl'
      WRITE(31,100) TIME,0D0,MASS0,MINO,MOUTO,QOLD,0D0,
     &    0D0,CUMDEF,PO(N),0,0D0,0,0D0
  100 FORMAT(10(ES24.15E3,','),I5,',',ES24.15E3,',',I5,',',
     &       ES24.15E3)
  200 CONTINUE
      IF (TIME.GE.DURATION-1D-9) GOTO 900
      H=DMIN1(H,HMAX,DURATION-TIME)
C     HIT THE KNOWN DEMAND-RAMP BREAKPOINT EXACTLY.
      IF (TIME.LT.TRAMP-1D-9) H=DMIN1(H,TRAMP-TIME)
C     BOUNDARY CHANGE RESOLUTION: AT MOST 1/8 OF RAMP DURATION.
      IF (TIME.LT.TRAMP-1D-9) H=DMIN1(H,TRAMP/8D0)
      REJECT=0
  300 CONTINUE
      IF (H.LT.HFLOOR) THEN
         WRITE(*,*) 'ADAPTIVE HMIN FAILURE',TIME,H
         STOP 5
      ENDIF
      TNEXT=TIME+H
      MOUTN=DEMAND_RAMP(TNEXT,MDOT0,MDOT1,TRAMP)
      CALL TRANSIENT_STEP(N,PO,MO,MINO,MOUTO,MOUTN,PIN,
     &     DX,H,THETA,D,A,T,Z,RS,MU,EPS,RTOL,STOL,
     &     MAXIT,0,U,INFO,NITER)
      NTOTAL=NTOTAL+1
      IF (INFO.NE.0) THEN
         REJECT=REJECT+1
         REJECTED=REJECTED+1
         IF (REJECT.GT.MAXREJ) THEN
            WRITE(*,*) 'NEWTON REJECTION LIMIT',TIME,H,INFO
            STOP 6
         ENDIF
         H=H*0.5D0
         GOTO 300
      ENDIF
      PN(0)=U(1)
      DO 310 I=0,N-1
         MN(I)=U(2*I+3)
         PN(I+1)=U(2*I+4)
  310 CONTINUE
      CALL LINEPACK_CZ(N,PN,DX,A,T,Z,RS,MASS1)
      QNEW=U(2)-MOUTN
      ETA=0D0
C     CURVATURE ESTIMATE: 2*|THETA-1/2|*H**2*Y''.
C     VARIABLE STEP SLOPE DIFFERENCE USES MIDPOINT SPACING.
C     ALL STATES SCALED WITH PHYSICAL PRESSURE/FLOW TOLERANCES.
      IF (STARTUP.EQ.0) THEN
         DO 320 I=1,2*N+2
            SCALE=1D0
            IF (MOD(I,2).EQ.1) SCALE=8D6
            IF (MOD(I,2).EQ.0) SCALE=100D0
            VAL=DABS((U(I)-PREV(I))/H-OLDS(I))
            ETA=DMAX1(ETA,2D0*DABS(THETA-0.5D0)*H*H*
     &             VAL/(H+HPREV)/SCALE)
  320    CONTINUE
C     ADD LINEPACK CHANGE AND MASS IMBALANCE AS GOALS.
         VAL=DABS((MASS1-MASS0)/H-
     &       (MASS0-OLDMASS)/HPREV)
         ETA=DMAX1(ETA,2D0*DABS(THETA-0.5D0)*H*H*
     &        VAL/(H+HPREV)/5000D0)
         VAL=DABS((QNEW-QOLD)/H-(QOLD-QPREV)/HPREV)
         ETA=DMAX1(ETA,2D0*DABS(THETA-0.5D0)*H*H*
     &        VAL/(H+HPREV)/5D0)
         ETA=ETA/TOL
      ENDIF
      IF (ETA.GT.1D0) THEN
         REJECT=REJECT+1
         REJECTED=REJECTED+1
         IF (REJECT.GT.MAXREJ) THEN
            WRITE(*,*) 'ERROR REJECTION LIMIT',TIME,H,ETA
            STOP 7
         ENDIF
         FAC=DMAX1(0.2D0,DMIN1(0.8D0,0.9D0/DSQRT(ETA)))
         H=H*FAC
         GOTO 300
      ENDIF
      BAL=MASS1-MASS0-H*(THETA*QNEW+(1D0-THETA)*QOLD)
      CUMDEF=CUMDEF+BAL
      CFL=CS*H/DX
      WRITE(31,100) TNEXT,H,MASS1,U(2),MOUTN,QNEW,
     & (MASS1-MASS0)/H,BAL,CUMDEF,PN(N),NITER,ETA,REJECT,CFL
      DO 330 I=1,2*N+2
         IF (STARTUP.EQ.0) THEN
            CONTINUE
         ENDIF
         OLDS(I)=(U(I)-PREV(I))/H
         PREV(I)=U(I)
  330 CONTINUE
C     PREV(I) MUST REPRESENT THE LAST ACCEPTED STATE ON FIRST STEP.
      DO 340 I=0,N
         PO(I)=PN(I)
  340 CONTINUE
      DO 350 I=0,N-1
         MO(I)=MN(I)
  350 CONTINUE
      OLDMASS=MASS0
      MASS0=MASS1
      QPREV=QOLD
      QOLD=QNEW
      MINO=U(2)
      MOUTO=MOUTN
      TIME=TNEXT
      HPREV=H
      STARTUP=0
      ACCEPTED=ACCEPTED+1
      IF (ETA.GT.1D-12) THEN
         FAC=DMAX1(0.5D0,DMIN1(2D0,0.9D0/DSQRT(ETA)))
      ELSE
         FAC=2D0
      ENDIF
      H=H*FAC
      GOTO 200
  900 CONTINUE
      CLOSE(31)
      WRITE(*,'(A,I0,A,I0,A,I0,A,ES12.4)')
     & 'accepted=',ACCEPTED,' rejected=',REJECTED,
     & ' attempts=',NTOTAL,' cumulative_defect_kg=',CUMDEF
      END
