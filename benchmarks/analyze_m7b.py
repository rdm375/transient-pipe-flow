#!/usr/bin/env python3
"""M7b reproducible sensor diagnostics; standard library only."""
import csv
import math
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent / 'results-m7b'
SENSORS = ('p25_pa', 'p50_pa', 'p75_pa', 'pout_pa')

def analyze(rows):
    groups = defaultdict(list)
    for row in rows:
        groups[int(row['case_id'])].append(row)
    output = []
    for case_id, history in sorted(groups.items()):
        history.sort(key=lambda row: float(row['time']))
        first, last = history[0], history[-1]
        initial = float(first['pout_pa'])
        result = dict(case_id=case_id, forcing=int(first['forcing']),
                      n=int(first['n']), dt=float(first['dt']),
                      theta=float(first['theta']))
        # 'Arrival' is explicitly a threshold crossing, not physical wave speed.
        # Threshold is 10% of maximum absolute deviation at that sensor.
        for sensor in SENSORS:
            data = [(float(r['time']), float(r[sensor])) for r in history]
            base = data[0][1]
            amp = max(abs(y-base) for _, y in data)
            threshold = 0.1 * amp
            arrival = next((t for t,y in data[1:] if amp > 0 and
                            abs(y-base) >= threshold), math.nan)
            lo = min(data, key=lambda v: v[1])
            hi = max(data, key=lambda v: v[1])
            tag = sensor.split('_')[0]
            result.update({f'{tag}_arrival10_s':arrival,
                           f'{tag}_min_pa':lo[1],f'{tag}_min_time_s':lo[0],
                           f'{tag}_max_pa':hi[1],f'{tag}_max_time_s':hi[0],
                           f'{tag}_max_delta_pa':amp})
        result['max_step_mass_defect_kg'] = max(abs(float(r['step_mass_defect_kg'])) for r in history)
        result['max_cum_mass_defect_kg'] = max(abs(float(r['cum_mass_defect_kg'])) for r in history)
        result['relative_cum_mass_defect'] = result['max_cum_mass_defect_kg']/float(first['linepack_kg'])
        # Count reversals of discrete outlet-pressure increments, excluding tiny changes.
        values = [float(r['pout_pa']) for r in history]
        increments = [b-a for a,b in zip(values,values[1:])]
        tol = max(1e-5,1e-7*max(abs(v-initial) for v in values))
        signs = [1 if d>0 else -1 for d in increments if abs(d)>tol]
        result['pout_slope_reversals'] = sum(a!=b for a,b in zip(signs,signs[1:]))
        result['final_pout_pa'] = float(last['pout_pa'])
        output.append(result)
    return output

def main():
    with (ROOT/'sensors.csv').open(newline='') as f:
        data=list(csv.DictReader(f))
    rows=analyze(data)
    with (ROOT/'metrics.csv').open('w',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=list(rows[0]))
        writer.writeheader();writer.writerows(rows)
    worst=max(row['relative_cum_mass_defect'] for row in rows)
    assert len(rows)==54, len(rows)
    assert worst < 1e-7, f'mass balance failed: {worst}'
    md=['# M7b — Sensor and damping diagnostics','',
        'Generated by `python3 benchmarks/analyze_m7b.py`.','',
        '## Evidence and limitations','',
        '- 54 runs: 3 forcing histories × 2 grids × 3 timesteps × 3 theta weights.',
        '- Sensors at 25%, 50%, 75%, and 100% of pipe length; output in SI units.',
        '- Arrival10 is first crossing of 10% of **each sensor’s own** maximum absolute pressure departure from its initial value. It is not a characteristic speed or a phase velocity.',
        '- Extrema and their times are sampled at output timesteps; no interpolation is performed.',
        '- Slope reversals are a heuristic for ringing, **not** proof of numerical instability or nonphysical oscillations.',
        '- Conservation defect is computed from the same theta-weighted boundary flux convention used by the discrete method; it is a numerical consistency check, not physical validation.',
        '- Step and pulse boundary discontinuities are sampled at step endpoints; errors from that convention are not separable from time-integration errors in these results.',
        '- Comparisons across grid and timestep are empirical; no analytical wave solution, exact damping factor, or uncertainty bound is claimed.',
        '',f'- Maximum normalized cumulative mass defect across cases: `{worst:.6e}`.','',
        '## Selected pressure metrics','',
        '| Forcing | N | dt (s) | θ | Outlet minimum (MPa) | Time (s) | Slope reversals |',
        '|---|---:|---:|---:|---:|---:|---:|']
    for row in rows:
        if row['n']==40 and row['dt']==60.0:
            md.append(f"| {row['forcing']} | {row['n']} | {row['dt']:g} | {row['theta']:.2f} | {row['pout_min_pa']/1e6:.6f} | {row['pout_min_time_s']:g} | {row['pout_slope_reversals']} |")
    md.extend(['','## Next validation work','',
               'A true linearized dispersion/damping comparison requires deriving and checking the discrete symbol with the exact staggered boundary conditions; do not interpret these sensor metrics as that comparison.',
               'The present sensor time histories permit follow-up arrival and attenuation analysis, but the threshold-based arrival metric must be validated against timestep and grid changes before interpreting it physically.',''])
    (ROOT/'REPORT.md').write_text('\n'.join(md))
    print(f'PASS: {len(rows)} cases; max relative mass defect {worst:.3e}')

if __name__=='__main__':
    main()
